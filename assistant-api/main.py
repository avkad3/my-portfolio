"""
ASK ADITYA — FastAPI service.

User → Next.js UI → /api/ask (Next) → this service → knowledge base → retrieve (BM25) → LLM → response

The knowledge base is generated by the Next.js site (GET /api/knowledge), so the
assistant can never drift from what the portfolio actually says.

Run:
    pip install -r requirements.txt
    export KNOWLEDGE_URL=http://localhost:3000/api/knowledge   # or place knowledge.json next to this file
    export ANTHROPIC_API_KEY=...                                # optional; without it answers are extractive
    uvicorn main:app --port 8000

Then set ASSISTANT_API_URL=http://localhost:8000 for the Next.js app.
"""

from __future__ import annotations

import json
import math
import os
import re
import urllib.request
from collections import Counter
from pathlib import Path

from fastapi import FastAPI, HTTPException
from fastapi.middleware.cors import CORSMiddleware
from pydantic import BaseModel, Field

MODEL = os.getenv("ASSISTANT_MODEL", "claude-opus-5-5")
STOP = set(
    "a an the of and or to in on for with by is are was were be has have had what which who how does did do "
    "aditya his he him me tell about show any project projects built build use used uses using that this from at as it its can".split()
)
SYSTEM_PROMPT = (
    "You are ASK ADITYA, the assistant on Aditya Vijay Kumar's portfolio website. "
    "Answer only from the portfolio context provided in the user turn. If the context does not contain the answer, "
    "say you can only answer from the portfolio and suggest what the visitor could ask instead. "
    "Never invent employers, metrics, links, dates or technologies. Refer to Aditya in the third person. "
    "Keep answers short: two to five sentences or a brief bulleted list, plain text without markdown headings."
)


def load_docs() -> list[dict]:
    url = os.getenv("KNOWLEDGE_URL")
    if url:
        with urllib.request.urlopen(url, timeout=10) as r:
            return json.load(r)["docs"]
    path = Path(__file__).with_name("knowledge.json")
    if path.exists():
        return json.loads(path.read_text(encoding="utf-8"))["docs"]
    raise RuntimeError("Set KNOWLEDGE_URL or provide knowledge.json (download it from /api/knowledge).")


def tokenize(text: str) -> list[str]:
    return [t for t in re.findall(r"[a-z0-9+#.\-]+", text.lower()) if len(t) > 1 and t not in STOP]


class Index:
    """Small BM25 index over the portfolio documents."""

    def __init__(self, docs: list[dict], k1: float = 1.4, b: float = 0.72):
        self.docs, self.k1, self.b = docs, k1, b
        self.toks = [tokenize(f"{d['title']} {d['title']} {d['text']}") for d in docs]
        self.tf = [Counter(t) for t in self.toks]
        self.avg = sum(map(len, self.toks)) / max(len(self.toks), 1)
        df: Counter[str] = Counter()
        for t in self.toks:
            df.update(set(t))
        n = len(docs)
        self.idf = {term: math.log(1 + (n - c + 0.5) / (c + 0.5)) for term, c in df.items()}

    def search(self, query: str, k: int = 4) -> list[tuple[dict, float]]:
        terms = tokenize(query)
        scored = []
        for i, doc in enumerate(self.docs):
            s = 0.0
            for term in terms:
                f = self.tf[i].get(term, 0)
                if f:
                    s += self.idf.get(term, 0) * f * (self.k1 + 1) / (f + self.k1 * (1 - self.b + self.b * len(self.toks[i]) / self.avg))
            if s > 0:
                scored.append((doc, s))
        return sorted(scored, key=lambda x: -x[1])[:k]


def make_client():
    try:
        import anthropic
    except ImportError:
        return None
    if not (os.getenv("ANTHROPIC_API_KEY") or os.getenv("ANTHROPIC_AUTH_TOKEN") or os.getenv("ANTHROPIC_PROFILE")):
        return None
    return anthropic.Anthropic()


app = FastAPI(title="ASK ADITYA")
app.add_middleware(CORSMiddleware, allow_origins=os.getenv("CORS_ORIGINS", "*").split(","), allow_methods=["POST", "GET"], allow_headers=["*"])
INDEX = Index(load_docs())
CLIENT = make_client()


class Ask(BaseModel):
    question: str = Field(min_length=1, max_length=300)


@app.get("/health")
def health():
    return {"ok": True, "docs": len(INDEX.docs), "llm": bool(CLIENT), "model": MODEL if CLIENT else None}


@app.post("/ask")
def ask(body: Ask):
    hits = INDEX.search(body.question)
    sources = [{"title": d["title"], "href": d["href"]} for d, _ in hits]
    if not hits:
        return {"answer": "I can only answer from Aditya's portfolio, and I couldn't find anything on that.", "sources": [], "mode": "fastapi · retrieval"}

    context = "\n\n".join(f"[{d['title']}]\n{d['text']}" for d, _ in hits)
    if CLIENT is None:
        top = hits[0][0]
        return {"answer": f"{top['title']}\n{top['text'][:600]}", "sources": sources[:2], "mode": "fastapi · retrieval"}

    import anthropic

    try:
        response = CLIENT.beta.messages.create(
            model=MODEL,
            max_tokens=1024,
            system=SYSTEM_PROMPT,
            output_config={"effort": "low"},
            betas=["server-side-fallback-2026-07-01"],
            fallbacks="default",
            messages=[{"role": "user", "content": f"<portfolio_context>\n{context}\n</portfolio_context>\n\nQuestion: {body.question}"}],
        )
    except anthropic.RateLimitError:
        raise HTTPException(status_code=429, detail="Assistant is busy, try again shortly.")
    except (anthropic.APIStatusError, anthropic.APIConnectionError) as e:
        raise HTTPException(status_code=502, detail=f"LLM unavailable: {type(e).__name__}")

    if response.stop_reason == "refusal":
        answer = "I can't help with that one. Ask about Aditya's projects, experience or stack."
    else:
        answer = "".join(b.text for b in response.content if b.type == "text").strip()
    return {"answer": answer, "sources": sources, "mode": f"fastapi · {MODEL}"}
